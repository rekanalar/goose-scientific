#!/usr/bin/env python3
"""Write test/suite/suite.goose, the index of the test groups.

Run it from anywhere with: python3 -I test/gen_suite.py [--list]

It scans each test/suite/<name>_tests.goose for the lines `fn test_...(`.
It writes the functions that test/run.goose calls:
  run_all       runs every test that no other test calls
  run_group     runs every test of one group
  run_test      runs one test by name
  run_test_in   runs one test when it belongs to the group
  print_groups  prints the names of the groups
A group may have more than one file. A file `<group>_N_tests.goose` with a
number N joins the group of `<group>_tests.goose`: `dist_tests.goose` and
`dist_2_tests.goose` are the files of the group `dist`.
A test that another test calls runs inside that test, so the full run
does not run it twice. Goose has no reflection, so the index lists the
names. Run this script again after you add, move or rename a test.
It fails on a test name that two files hold and on a file above LIMIT
lines. The option --list prints each group with its tests.
"""
import glob
import os
import re
import sys

LIMIT = 1000
HERE = os.path.dirname(os.path.abspath(__file__))
SUITE = os.path.join(HERE, 'suite')


def group_of(path):
    """The group of a file: dist_2_tests.goose is the group dist."""
    stem = os.path.basename(path)[:-len('.goose')]
    if not stem.endswith('_tests'):
        raise SystemExit('%s: the name must end with _tests' % path)
    stem = stem[:-len('_tests')]
    m = re.match(r'^(.*)_(\d+)$', stem)
    if m:
        stem = m.group(1)
    return stem


def main():
    groups = {}
    text = {}
    tests = {}
    for path in sorted(glob.glob(os.path.join(SUITE, '*_tests.goose'))):
        src = open(path).read()
        if src.count('\n') > LIMIT:
            raise SystemExit('%s holds more than %d lines' % (path, LIMIT))
        mod = os.path.basename(path)[:-len('.goose')]
        m = re.search(r'^namespace (\w+);', src, re.M)
        if not m or m.group(1) != mod:
            raise SystemExit('%s: the namespace must be %s' % (path, mod))
        g = group_of(path)
        groups.setdefault(g, []).append(mod)
        text[mod] = src
        tests[mod] = re.findall(r'^fn (test_\w+)\(', src, re.M)
    seen = {}
    for mod in sorted(tests):
        for n in tests[mod]:
            if n in seen:
                raise SystemExit('the test %s is in %s and %s' % (n, seen[n], mod))
            seen[n] = mod
    if '--list' in sys.argv:
        for g in sorted(groups):
            names = [n for mod in groups[g] for n in tests[mod]]
            print(g, len(names), ' '.join(names))
        return
    # a test that another test calls runs inside that test
    callee = set()
    for mod, src in text.items():
        for line in src.split('\n'):
            if line.lstrip().startswith('//') or line.startswith('fn '):
                continue
            callee.update(re.findall(r'(?<![\w])(test_\w+)\(', line))
    out = ['// Generated by test/gen_suite.py. Do not edit by hand.',
           'namespace suite;', '', 'import std;']
    for mod in sorted(text):
        out.append('import %s;' % mod)
    out += ['',
            '// run_all runs every test that no other test calls.',
            'fn run_all() {']
    for g in sorted(groups):
        for mod in groups[g]:
            for n in tests[mod]:
                if n not in callee:
                    out.append('    %s::%s();' % (mod, n))
    out += ['}', '', '// run_group runs every test of one group. It tells whether the group exists.',
            'fn run_group(g: const u8[:]) -> bool {']
    for g in sorted(groups):
        out.append('    if g == "%s" {' % g)
        for mod in groups[g]:
            for n in tests[mod]:
                out.append('        %s::%s();' % (mod, n))
        out += ['        return true;', '    }']
    out += ['    return false;', '}', '',
            '// run_test runs one test by name. It tells whether the test exists.',
            'fn run_test(t: const u8[:]) -> bool {']
    for mod in sorted(text):
        for n in tests[mod]:
            out.append('    if t == "%s" { %s::%s(); return true; }' % (n, mod, n))
    out += ['    return false;', '}', '',
            '// run_test_in runs one test when it belongs to the group.',
            'fn run_test_in(g: const u8[:], t: const u8[:]) -> bool {']
    for g in sorted(groups):
        out.append('    if g == "%s" {' % g)
        for mod in groups[g]:
            for n in tests[mod]:
                out.append('        if t == "%s" { %s::%s(); return true; }' % (n, mod, n))
        out += ['        return false;', '    }']
    out += ['    return false;', '}', '',
            'fn print_groups() {',
            '    print("groups: %s\\n");' % ' '.join(sorted(groups)),
            '}', '']
    with open(os.path.join(SUITE, 'suite.goose'), 'w') as f:
        f.write('\n'.join(out))
    print('groups', len(groups), 'files', len(text), 'tests', len(seen),
          'run_all', len(seen) - len(callee))


main()
