#!/usr/bin/env python3
"""Write the pins of the tests of the chain product and the two calls.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. Every family of cases holds the
inputs and the expected results. A ragged list is two buffers: the
values joined end to end, and the length of each part. The order of a
chain of matrices gives the number of the arrays of every case. The
calls over the axes hold one array per case and a list of axes. The
calls over the values hold one, two or three arrays per case.
"""
import numpy as np

OUT = "test/suite/multi_dot_apply_pins.goose"


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in values)))


def ragged(lines, name, parts):
    """Write a ragged list as the values and the length of each part."""
    flat = [v for p in parts for v in p]
    emit(lines, name + "_D", flat)
    emit(lines, name + "_L", [len(p) for p in parts])


def shape_of(a):
    """The shape of a NumPy array, as a list of numbers."""
    return [float(n) for n in a.shape]


def result_shape(a):
    """The shape of a result. The package holds no array of no
    dimension, so an empty shape holds one dimension of one."""
    if len(a.shape) == 0:
        return [1.0]
    return shape_of(a)


def chain_cases():
    """The chains of matrices. The cases hold two, three, four and six
    arrays, a vector at the first place, a vector at the last place and
    a chain of two vectors."""
    rng = np.random.default_rng(31)
    cases = []
    cases.append([np.array([[1.0, 2.0, 3.0]]), np.array([[4.0, 5.0], [6.0, 7.0], [8.0, 9.0]])])
    cases.append([rng.normal(size=(2, 3)), rng.normal(size=(3, 4))])
    cases.append([rng.normal(size=(2, 3)), rng.normal(size=(3, 4)), rng.normal(size=(4, 5))])
    cases.append([rng.normal(size=(2, 3)), rng.normal(size=(3, 4)),
                  rng.normal(size=(4, 5)), rng.normal(size=(5, 2))])
    cases.append([rng.normal(size=(2, 4)), rng.normal(size=(4, 3)),
                  rng.normal(size=(3, 5)), rng.normal(size=(5, 2)),
                  rng.normal(size=(2, 6)), rng.normal(size=(6, 1))])
    cases.append([rng.normal(size=3), rng.normal(size=(3, 4))])
    cases.append([rng.normal(size=(2, 3)), rng.normal(size=3)])
    cases.append([rng.normal(size=3), rng.normal(size=3)])
    cases.append([np.eye(2), np.eye(2), np.eye(2)])
    cases.append([np.ones((1, 1)), np.ones((1, 1)), np.ones((1, 1)), np.ones((1, 1))])
    cases.append([rng.normal(size=(5, 2)), rng.normal(size=(2, 7)),
                  rng.normal(size=(7, 3)), rng.normal(size=(3, 4)),
                  rng.normal(size=(4, 6))])
    cases.append([rng.normal(size=(3, 1)), rng.normal(size=(1, 5))])
    return cases


def axis_cases():
    """The calls over the axes. The array holds three dimensions and the
    lists of axes hold a list, a negative list, a list with a repeat and
    an empty list."""
    a = np.arange(24.0).reshape(2, 3, 4)
    b = np.arange(12.0).reshape(3, 4)
    cases = []
    cases.append((a, [0]))
    cases.append((a, [1]))
    cases.append((a, [2]))
    cases.append((a, [0, 2]))
    cases.append((a, [-1]))
    cases.append((a, [-2]))
    cases.append((a, [1, 1]))
    cases.append((a, [0, 0]))
    cases.append((a, []))
    cases.append((b, [0]))
    cases.append((b, [1]))
    cases.append((b, [0, 1]))
    cases.append((b, [-1]))
    return cases


def value_cases():
    """The calls over the values. The cases hold one, two and three
    arrays, and a broadcast of a row and a column."""
    rng = np.random.default_rng(47)
    cases = []
    cases.append(([rng.normal(size=5)],))
    cases.append(([rng.normal(size=(2, 3))],))
    cases.append(([rng.normal(size=3)],))
    cases.append(([rng.normal(size=3), rng.normal(size=3)],))
    cases.append(([rng.normal(size=3), rng.normal(size=(2, 1))],))
    cases.append(([rng.normal(size=(2, 1)), rng.normal(size=3)],))
    cases.append(([rng.normal(size=(2, 3)), rng.normal(size=(1, 3))],))
    cases.append(([rng.normal(size=2), rng.normal(size=2), rng.normal(size=2)],))
    cases.append(([rng.normal(size=3), rng.normal(size=(2, 1)), rng.normal(size=1)],))
    cases.append(([rng.normal(size=(1, 4)), rng.normal(size=(4, 1))],))
    return cases


def main():
    lines = ["// Generated by test/gen_multi_dot_apply.py. Do not edit by hand.",
             "",
             "// The pins of the tests of the chain product and the two calls.",
             "// They come from NumPy 2.5.4.",
             "namespace multi_dot_apply_pins;",
             ""]

    cc = chain_cases()
    parts = []
    for c in cc:
        for a in c:
            parts.append(list(a.ravel()))
    ragged(lines, "CH_VAL", parts)
    ragged(lines, "CH_SH", [shape_of(a) for c in cc for a in c])
    emit(lines, "CH_N", [len(c) for c in cc])
    outs = []
    oshapes = []
    for c in cc:
        r = np.linalg.multi_dot(c)
        outs.append(list(np.atleast_1d(r).ravel()))
        oshapes.append(result_shape(r))
    ragged(lines, "CH_OUT", outs)
    ragged(lines, "CH_OUT_SH", oshapes)

    ac = axis_cases()
    ragged(lines, "AO_IN", [list(a.ravel()) for a, _ in ac])
    ragged(lines, "AO_SH", [shape_of(a) for a, _ in ac])
    ragged(lines, "AO_AX", [[float(x) for x in axes] for _, axes in ac])
    for tag, func in [("SUM", np.sum), ("PROD", np.prod), ("CUMSUM", np.cumsum)]:
        outs = []
        oshapes = []
        for a, axes in ac:
            r = np.apply_over_axes(func, a, axes)
            outs.append(list(np.atleast_1d(r).ravel()))
            oshapes.append(result_shape(r))
        ragged(lines, "AO_%s_OUT" % tag, outs)
        ragged(lines, "AO_%s_OUT_SH" % tag, oshapes)

    vc = value_cases()
    for tag, n in [("V1", 1), ("V2", 2), ("V3", 3)]:
        sel = [c for c in vc if len(c[0]) == n]
        parts = []
        for c in sel:
            for a in c[0]:
                parts.append(list(a.ravel()))
        ragged(lines, "%s_VAL" % tag, parts)
        ragged(lines, "%s_SH" % tag, [shape_of(a) for c in sel for a in c[0]])
        emit(lines, "%s_N" % tag, [len(c[0]) for c in sel])
        outs = []
        oshapes = []
        for c in sel:
            if n == 1:
                f = np.vectorize(lambda x: x * x + 1.0)
            elif n == 2:
                f = np.vectorize(lambda x, y: x + y)
            else:
                f = np.vectorize(lambda x, y, z: x + y + z)
            r = f(*c[0])
            outs.append(list(np.atleast_1d(r).ravel()))
            oshapes.append(result_shape(r))
        ragged(lines, "%s_OUT" % tag, outs)
        ragged(lines, "%s_OUT_SH" % tag, oshapes)

    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s" % OUT)
    print("chain cases %d, axis cases %d, value cases %d" %
          (len(cc), len(axis_cases()), len(vc)))


if __name__ == "__main__":
    main()
