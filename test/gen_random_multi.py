#!/usr/bin/env python3
"""Write the pins of the tests of the random laws of a vector.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. The tests draw points from the
generator of the package and compare them with these values. The stream
of the package differs from the stream of NumPy, so the law is the
reference.

The Dirichlet law of a row of concentrations has the mean of each
component at the concentration over the sum of the concentrations. The
normal law of a vector has the mean of the caller and the covariance of
the caller. NumPy 2.5.4 gives the same values.
"""
import numpy as np

OUT = "test/suite/random_multi_pins.goose"

DIRICHLET = [
    [1.0, 2.0, 3.0],
    [2.0, 5.0, 7.0, 3.0],
]

MVN = [
    ([0.0, 0.0], [[2.0, 0.5], [0.5, 1.0]]),
    ([1.0, -2.0, 0.5], [[3.0, 0.4, 0.1], [0.4, 1.5, 0.2], [0.1, 0.2, 2.0]]),
    ([-1.0], [[4.0]]),
]


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in values)))


def main():
    lines = ["// Generated by test/gen_random_multi.py. Do not edit by hand.",
             "",
             "// The pins of the tests of the random laws of a vector.",
             "// They come from NumPy 2.5.4.",
             "// DIR_A holds the rows of the concentrations. DIR_M holds the mean",
             "// of each component of each row.",
             "// MVN_M holds the mean of each law. MVN_C holds the covariance of",
             "// each law, row by row.",
             "namespace random_multi_pins;",
             ""]
    for k, alpha in enumerate(DIRICHLET):
        emit(lines, "DIR_A%d" % (k + 1), alpha)
        a = np.array(alpha)
        emit(lines, "DIR_M%d" % (k + 1), a / a.sum())
    for k, (mean, cov) in enumerate(MVN):
        emit(lines, "MVN_M%d" % (k + 1), mean)
        c = np.array(cov)
        emit(lines, "MVN_C%d" % (k + 1), c.reshape(-1))
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s, %d laws" % (OUT, len(DIRICHLET) + len(MVN)))


if __name__ == "__main__":
    main()
