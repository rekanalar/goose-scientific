#!/usr/bin/env python3
"""Write the pins of the archive of the sparse formats and the incomplete factorization.

The script needs Python 3 with NumPy 2.5.4 and SciPy 1.18.1. It runs
from the maintainer, from the root of the package:

    /path/to/venv/bin/python -I test/gen_sparse_npz.py

The user of the package installs nothing. The file the script writes
holds numbers only.

A name of a member of an archive holds its letters as the codes of the
bytes, with a span of a start and a length. The sizes hold the length
of the body of every member of the archives of SciPy, which wrote them
with stored members. The bytes of the whole archive of the format dia
hold the same rule, one number per byte.

A case of the incomplete factorization holds the side, the count of the
entries, the place of the rows, the place of the right side, the place
of the answer, the drop tolerance and the fill factor. The answer comes
from the solve of the factorization of SciPy.
"""
import io
import zipfile

import numpy as np
import scipy.sparse as sp
from scipy.sparse.linalg import spilu

OUT = "test/suite/sparse_npz_pins.goose"

FORMATS = ["csr", "csc", "bsr", "dia", "coo"]


def num_list(vs):
    return "[" + ", ".join(repr(float(v)) for v in vs) + "]"


def archive_members(matrix):
    """Write an archive of SciPy with stored members and name its members."""
    bio = io.BytesIO()
    sp.save_npz(bio, matrix, compressed=False)
    bio.seek(0)
    z = zipfile.ZipFile(bio)
    names = []
    sizes = []
    for info in z.infolist():
        if info.compress_type != 0:
            raise SystemExit("scipy wrote a compressed member")
        names.append(info.filename.encode("ascii"))
        sizes.append(info.file_size)
    return names, sizes


def main():
    out = []
    out.append("// Generated by test/gen_sparse_npz.py. Do not edit by hand.")
    out.append("")
    out.append("// The pins of the archive of the sparse formats and of the")
    out.append("// incomplete factorization. They come from SciPy 1.18.1 and")
    out.append("// NumPy 2.5.4.")
    out.append("namespace sparse_npz_pins;")
    out.append("")

    # One matrix of four sides, in the five formats of SciPy. The
    # blocks of the format bsr hold two sides of two.
    dense = np.array([
        [1.0, 0.0, 3.0, 0.0],
        [0.0, 4.0, 0.0, 0.0],
        [5.0, 0.0, 6.0, 7.0],
        [0.0, 8.0, 0.0, 9.0],
    ])
    mats = {
        "csr": sp.csr_matrix(dense),
        "csc": sp.csc_matrix(dense),
        "bsr": sp.bsr_matrix(dense, blocksize=(2, 2)),
        "dia": sp.dia_matrix(dense),
        "coo": sp.coo_matrix(dense),
    }

    all_names = []
    all_spans = []
    all_sizes = []
    counts = []
    for fmt in FORMATS:
        names, sizes = archive_members(mats[fmt])
        counts.append(len(names))
        for nm, sz in zip(names, sizes):
            all_spans.append((len(all_names), len(nm)))
            all_names.extend(nm)
            all_sizes.append(sz)

    out.append("// The names of the members of the five archives of SciPy, as the")
    out.append("// codes of the bytes. A span holds a start and a length.")
    out.append("const A_NAMES: f64[>..] = " + num_list(all_names) + ";")
    out.append("const A_NAME_SPANS: f64[>..] = "
               + num_list([v for pair in all_spans for v in pair]) + ";")
    out.append("// The length of the body of every member, in the order of the")
    out.append("// archive, and the count of the members of every archive.")
    out.append("const A_SIZES: f64[>..] = " + num_list(all_sizes) + ";")
    out.append("const A_COUNTS: f64[>..] = " + num_list(counts) + ";")
    out.append("// The format of every archive, in the order of the five formats.")
    out.append("const A_KINDS: f64[>..] = [0.0, 1.0, 2.0, 3.0, 4.0];")
    out.append("// The two sides of the matrix of the archives, and the values")
    out.append("// that a read of any archive gives.")
    out.append("const A_SHAPE: f64[>..] = " + num_list(dense.shape) + ";")
    out.append("const A_DENSE: f64[>..] = " + num_list(dense.ravel()) + ";")
    out.append("")

    # The bytes of the five archives of SciPy, one number per byte. A
    # span holds a start and a length. The read of every archive runs
    # on the bytes of SciPy alone.
    all_bytes = []
    byte_spans = []
    for fmt in FORMATS:
        bio = io.BytesIO()
        sp.save_npz(bio, mats[fmt], compressed=False)
        data = bio.getvalue()
        byte_spans.append((len(all_bytes), len(data)))
        all_bytes.extend(data)
    out.append("// The bytes of the five archives of SciPy, one number per")
    out.append("// byte. A span holds a start and a length.")
    out.append("const Z_BYTES: f64[>..] = " + num_list(all_bytes) + ";")
    out.append("const Z_SPANS: f64[>..] = "
               + num_list([v for pair in byte_spans for v in pair]) + ";")
    out.append("")

    # The cases of the incomplete factorization. The answers come from
    # the solve of the factorization of SciPy. The factors of SciPy
    # hold another order than the factors of the package, so the two
    # agree only where the factorization drops nothing, which a drop
    # tolerance of zero holds for every case, and the first case holds
    # for its matrix of no fill.
    tri = np.array([
        [2.0, -1.0, 0.0, 0.0],
        [-1.0, 2.0, -1.0, 0.0],
        [0.0, -1.0, 2.0, -1.0],
        [0.0, 0.0, -1.0, 2.0],
    ])
    fill = np.array([
        [4.0, 1.0, 0.0, 2.0],
        [1.0, 5.0, 1.0, 0.0],
        [0.0, 1.0, 6.0, 1.0],
        [2.0, 0.0, 1.0, 7.0],
    ])
    # A matrix of twelve sides of many entries. The diagonal holds the
    # large values, so the factorization of the natural order holds no
    # pivot of zero.
    rng = np.random.default_rng(11)
    big = rng.uniform(-0.5, 0.5, (12, 12))
    big[np.diag_indices(12)] = rng.uniform(6.0, 9.0, 12)
    cases = [
        (tri, 0.5, 1.0),
        (tri, 0.0, 1.0),
        (fill, 0.0, 10.0),
        (fill, 0.0, 1.0),
        (big, 0.0, 10.0),
    ]
    rows_all = []
    cols_all = []
    vals_all = []
    b_all = []
    x_all = []
    case_rows = []
    for mat, tol, ff in cases:
        csr = sp.csr_matrix(mat)
        n = mat.shape[0]
        coo = csr.tocoo()
        at = len(rows_all)
        rows_all.extend(coo.row.astype(float))
        cols_all.extend(coo.col.astype(float))
        vals_all.extend(coo.data.astype(float))
        b = np.linspace(1.0, 2.0, n)
        x = spilu(sp.csc_array(mat), drop_tol=tol, fill_factor=ff,
                  drop_rule="basic").solve(b)
        if np.max(np.abs(x)) == 0.0:
            raise SystemExit("the answer of a case holds zero alone")
        b_at = len(b_all)
        b_all.extend(b.astype(float))
        x_at = len(x_all)
        x_all.extend(x.astype(float))
        case_rows.extend([float(n), float(csr.nnz), float(at), float(b_at),
                          float(x_at), tol, ff])
    out.append("// The cases of the incomplete factorization. A case holds the")
    out.append("// side, the count of the entries, the place of the rows, the")
    out.append("// place of the right side, the place of the answer, the drop")
    out.append("// tolerance and the fill factor.")
    out.append("const S_CASES: f64[>..] = " + num_list(case_rows) + ";")
    out.append("const S_ROWS: f64[>..] = " + num_list(rows_all) + ";")
    out.append("const S_COLS: f64[>..] = " + num_list(cols_all) + ";")
    out.append("const S_VALS: f64[>..] = " + num_list(vals_all) + ";")
    out.append("const S_B: f64[>..] = " + num_list(b_all) + ";")
    out.append("// The answers of the solve of SciPy, one value per place of")
    out.append("// the right side.")
    out.append("const S_X: f64[>..] = " + num_list(x_all) + ";")

    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
