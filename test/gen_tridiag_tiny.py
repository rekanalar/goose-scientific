#!/usr/bin/env python3
"""Write the pins of the tridiagonal scale tests.

The script needs SciPy 1.18.1 and NumPy 2.5.4. It runs them from the
maintainer. The user of the package installs nothing.

The file it writes holds numbers only. For two unit matrices it holds the
entries and the values that SciPy gives at each scale. The test multiplies
the entries by the scale and compares the values.
"""
import numpy as np
from scipy.linalg import eigvalsh_tridiagonal

OUT = "test/suite/tridiag_tiny_pins.goose"
SCALES = [1e-20, 1e-100, 1e-300, 1e154, 1e300]


def emit(lines, name, values):
    lines.append(f"const {name}: f64[>..] = [{', '.join(repr(float(v)) for v in values)}];")


def main():
    rng = np.random.default_rng(5)
    mats = {
        "S4": (np.array([1.0, 2.0, 3.0, 4.0]), np.array([0.5, 0.25, 0.5])),
        "S200": (2.0 + rng.uniform(-0.5, 0.5, 200), rng.uniform(-1.0, 1.0, 199)),
    }
    lines = ["// Generated by test/gen_tridiag_tiny.py. Do not edit by hand.", "",
             "// The pins of the scale tests. They come from SciPy 1.18.1.",
             "namespace tridiag_tiny_pins;", ""]
    emit(lines, "SCALES", SCALES)
    for name, (d, e) in mats.items():
        emit(lines, name + "_D", d)
        emit(lines, name + "_E", e)
        emit(lines, name + "_WU", eigvalsh_tridiagonal(d, e))
        for i, s in enumerate(SCALES):
            emit(lines, f"{name}_W{i}", eigvalsh_tridiagonal(d * s, e * s))
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
