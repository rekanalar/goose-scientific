#!/usr/bin/env python3
"""Write the pins of the tests of the text calls.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. A text is a run of byte values in
a list, and a second list holds the start and the length of each text. A
length of -1 means that NumPy raised an error for the case. A float case
holds the number, a code for the number (0 finite, 1 nan, 2 inf, 3
-inf) and the options: precision (-1 for none), unique, fractional, the
trim as a byte, sign, pad_left, pad_right, min_digits and exp_digits
(-1 for none).

A width of -1 in the rows of binary_repr means that the number has no
width. NumPy calls that case without a width.
"""
import random
import warnings

import numpy as np

warnings.simplefilter('ignore')
OUT = "test/suite/array_text_pins.goose"

VALUES = [0.0, -0.0, 1.0, -1.0, 0.5, 0.1, 1.5, 2.5, 0.375, 0.625, 123.25, 123.456,
          99.99, 0.099, 9.5, 1e-5, 1e-7, 0.0001234, 123456.0, 1e15, 1e16, 1e22,
          1.5e300, 5e-324, 1.7976931348623157e308, 0.30000000000000004,
          123456789.123, 2.675, 0.00123456, 1234.5, -0.001, -123.456, 1e100, 3.0e-10]
OPTS = [
    {}, {'precision': 3}, {'precision': 0}, {'precision': 1}, {'precision': 8},
    {'unique': False, 'precision': 2}, {'unique': False, 'precision': 0},
    {'unique': False, 'precision': 5}, {'unique': False, 'precision': 17},
    {'unique': False, 'precision': 3, 'fractional': False},
    {'precision': 3, 'fractional': False}, {'precision': 1, 'fractional': False},
    {'trim': '.'}, {'trim': '0'}, {'trim': '-'},
    {'unique': False, 'precision': 2, 'trim': '-'}, {'unique': False, 'precision': 3, 'trim': '0'},
    {'unique': False, 'precision': 3, 'trim': '.'},
    {'min_digits': 3}, {'min_digits': 2, 'precision': 4}, {'min_digits': 20}, {'min_digits': 2, 'trim': '-'},
    {'sign': True}, {'pad_left': 5}, {'pad_left': 3, 'sign': True},
    {'pad_right': 3}, {'pad_left': 4, 'pad_right': 4, 'trim': '-'}, {'pad_right': 2, 'trim': '0'},
    {'exp_digits': 0}, {'exp_digits': 1}, {'exp_digits': 3}, {'exp_digits': 5, 'precision': 2},
    {'precision': -2}, {'unique': False}, {'pad_left': -1}, {'min_digits': 3, 'precision': 2},
    {'fractional': False, 'precision': 0}, {'min_digits': 5, 'unique': False, 'precision': 6},
]
SPECIAL = [(float('nan'), 1), (float('inf'), 2), (-float('inf'), 3)]


def trim_byte(o):
    return ord(o.get('trim', 'k'))


def row(x, code, o):
    return [x, code, o.get('precision', -1), 1 if o.get('unique', True) else 0,
            1 if o.get('fractional', True) else 0, trim_byte(o), 1 if o.get('sign') else 0,
            o.get('pad_left') or 0, o.get('pad_right') or 0, o.get('min_digits') or 0,
            -1 if o.get('exp_digits') is None else o['exp_digits']]


def kwargs(o, sci):
    k = dict(o)
    if sci:
        k.pop('fractional', None)
        k.pop('pad_right', None)
    return k


def call(sci, x, o):
    f = np.format_float_scientific if sci else np.format_float_positional
    k = kwargs(o, sci)
    if not sci:
        k.pop('exp_digits', None)
    try:
        return f(x, **k)
    except (ValueError, TypeError):
        return None


class Texts:
    def __init__(self):
        self.bytes = []
        self.spans = []

    def add(self, s):
        if s is None:
            self.spans += [0, -1]
            return
        self.spans += [len(self.bytes), len(s)]
        self.bytes += [ord(c) for c in s]


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" % (name, ", ".join(repr(float(v)) for v in values)))


def emit_int(lines, name, values):
    lines.append("const %s: i64[>..] = [%s];" % (name, ", ".join(str(int(v)) for v in values)))


def float_cases(sci):
    rows, texts = [], Texts()
    cases = [(v, 0, o) for v in VALUES for o in OPTS]
    for v, c in SPECIAL:
        cases += [(v, c, o) for o in OPTS[:3] + [{'sign': True}, {'pad_left': 6}]]
    rnd = random.Random(359)
    for _ in range(150):
        v = rnd.choice([1, -1]) * rnd.random() * 10.0 ** rnd.randint(-30, 30)
        cases.append((v, 0, rnd.choice([{}, {'precision': 5}, {'unique': False, 'precision': 9}])))
    for _ in range(60):
        cases.append((float(np.frombuffer(rnd.randbytes(8), dtype='<f8')[0]), 0, {}))
    for v, c, o in cases:
        x = v if c == 0 else 0.0
        if c == 0 and (v != v or v in (float('inf'), -float('inf'))):
            continue
        real = v
        rows += row(x, c, o)
        texts.add(call(sci, real, o))
    return rows, texts


def main():
    lines = ["// Generated by test/gen_array_text.py. Do not edit by hand.", "",
             "// The pins of the tests of the text calls. They come from NumPy 2.5.4.",
             "namespace array_text_pins;", ""]
    for sci, tag in ((False, "POS"), (True, "SCI")):
        rows, texts = float_cases(sci)
        emit(lines, tag + "_ROWS", rows)
        emit(lines, tag + "_BYTES", texts.bytes)
        emit(lines, tag + "_SPANS", texts.spans)
    # base_repr and binary_repr
    brows, btexts = [], Texts()
    nums = [0, 1, 5, -5, 255, -255, 35, -35, 10, 2 ** 31, -2 ** 31, 2 ** 62, 2 ** 63 - 1, -2 ** 63]
    for n in nums:
        for b in (2, 3, 8, 10, 16, 36, 1, 37):
            for p in (0, 3, -1):
                brows += [n, b, p]
                try:
                    btexts.add(np.base_repr(n, b, p))
                except ValueError:
                    btexts.add(None)
    emit_int(lines, "BASE_ROWS", brows)
    emit(lines, "BASE_BYTES", btexts.bytes)
    emit(lines, "BASE_SPANS", btexts.spans)
    nrows, ntexts = [], Texts()
    for n in nums:
        for w in (-1, 0, 1, 3, 4, 8, 16, 32, 64, 70):
            nrows += [n, w]
            try:
                if w == -1:
                    ntexts.add(np.binary_repr(n))
                else:
                    ntexts.add(np.binary_repr(n, w))
            except ValueError:
                ntexts.add(None)
    emit_int(lines, "BIN_ROWS", nrows)
    emit(lines, "BIN_BYTES", ntexts.bytes)
    emit(lines, "BIN_SPANS", ntexts.spans)
    # typename
    codes = ['S1', '?', 'b', 'B', 'h', 'H', 'i', 'I', 'l', 'L', 'q', 'Q', 'f', 'd', 'g',
             'F', 'D', 'G', 'S', 'U', 'V', 'O', 'e', 'x', '', 'f8']
    tn_in, tn_out = Texts(), Texts()
    for c in codes:
        tn_in.add(c)
        try:
            tn_out.add(np.typename(c))
        except KeyError:
            tn_out.add(None)
    emit(lines, "TYPENAME_IN_BYTES", tn_in.bytes)
    emit(lines, "TYPENAME_IN_SPANS", tn_in.spans)
    emit(lines, "TYPENAME_OUT_BYTES", tn_out.bytes)
    emit(lines, "TYPENAME_OUT_SPANS", tn_out.spans)
    # mintypecode: chars, set, default, result
    cases = [('FD', 'GDFgdf', 'd'), ('', 'GDFgdf', 'd'), ('bB', 'bB', 'x'), ('xy', '', 'z'),
             ('q', 'qL', 'd'), ('d', 'Df', 'd'), ('F', 'fd', 'd'), ('Fd', 'fd', 'd'),
             ('Fd', 'Fd', 'd'), ('fFd', 'fFd', 'd'), ('gd', 'gd', 'd'),
             ('f', 'GDFgdf', 'd'), ('ef', 'GDFgdf', 'd'), ('iF', 'GDFgdf', 'd'), ('dF', 'GDFgdf', 'd'),
             ('x', 'x', 'd'), ('Qq', 'QqLl', 'd'), ('?', '?bB', 'd')]
    mt = [Texts(), Texts(), Texts(), Texts()]
    for a, s, d in cases:
        mt[0].add(a)
        mt[1].add(s)
        mt[2].add(d)
        try:
            mt[3].add(np.mintypecode(a, typeset=s, default=d))
        except ValueError:
            mt[3].add(None)
    for t, n in zip(mt, ("MT_CHARS", "MT_SET", "MT_DEFAULT", "MT_OUT")):
        emit(lines, n + "_BYTES", t.bytes)
        emit(lines, n + "_SPANS", t.spans)
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
