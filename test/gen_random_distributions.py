#!/usr/bin/env python3
"""Write the pins of the tests of the continuous random laws.

The script needs NumPy 2.5.4 and SciPy 1.18.1. It runs from the
maintainer. The user of the package installs nothing.

The file it writes holds numbers only. Each law has 3 parameter sets.
A set holds the parameters, the mean, the variance and the quartiles
of the law, from scipy.stats. The tests draw numbers from the generator
of the package and compare them with these values. The stream of the
package differs from the stream of NumPy, so the law is the reference.
"""
import numpy as np
import scipy.stats as st

OUT = "test/suite/random_distributions_pins.goose"

# name: list of (parameters, scipy frozen law)
LAWS = {
    "GAMMA": [((0.5, 2.0), st.gamma(a=0.5, scale=2.0)),
              ((2.0, 1.5), st.gamma(a=2.0, scale=1.5)),
              ((9.0, 0.5), st.gamma(a=9.0, scale=0.5))],
    "LOGN": [((0.0, 0.25), st.lognorm(s=0.25, scale=np.exp(0.0))),
             ((0.5, 0.5), st.lognorm(s=0.5, scale=np.exp(0.5))),
             ((-1.0, 0.4), st.lognorm(s=0.4, scale=np.exp(-1.0)))],
    "CHI2": [((1.0,), st.chi2(1.0)), ((5.0,), st.chi2(5.0)), ((30.0,), st.chi2(30.0))],
    "BETA": [((2.0, 3.0), st.beta(2.0, 3.0)), ((0.5, 0.5), st.beta(0.5, 0.5)),
             ((5.0, 1.5), st.beta(5.0, 1.5))],
    "RAYL": [((0.5,), st.rayleigh(scale=0.5)), ((2.0,), st.rayleigh(scale=2.0)),
             ((10.0,), st.rayleigh(scale=10.0))],
    "WEIB": [((0.8,), st.weibull_min(c=0.8)), ((1.5,), st.weibull_min(c=1.5)),
             ((4.0,), st.weibull_min(c=4.0))],
    "GUMB": [((0.0, 1.0), st.gumbel_r(loc=0.0, scale=1.0)),
             ((1.0, 2.0), st.gumbel_r(loc=1.0, scale=2.0)),
             ((-3.0, 0.5), st.gumbel_r(loc=-3.0, scale=0.5))],
    "LOGI": [((0.0, 1.0), st.logistic(loc=0.0, scale=1.0)),
             ((-1.0, 3.0), st.logistic(loc=-1.0, scale=3.0)),
             ((5.0, 0.2), st.logistic(loc=5.0, scale=0.2))],
}


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in values)))


def main():
    lines = ["// Generated by test/gen_random_distributions.py. Do not edit by hand.",
             "",
             "// The pins of the tests of the continuous random laws.",
             "// They come from NumPy 2.5.4 and SciPy 1.18.1.",
             "// Each law holds 3 sets. P1 and P2 are the parameters, M the mean,",
             "// V the variance and Q the quartiles, three for each set.",
             "namespace random_distributions_pins;",
             ""]
    for name, sets in LAWS.items():
        n = len(sets[0][0])
        for k in range(n):
            emit(lines, "%s_P%d" % (name, k + 1), [s[0][k] for s in sets])
        emit(lines, name + "_M", [s[1].mean() for s in sets])
        emit(lines, name + "_V", [s[1].var() for s in sets])
        emit(lines, name + "_Q", [s[1].ppf(q) for s in sets for q in (0.25, 0.5, 0.75)])
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s, %d laws" % (OUT, len(LAWS)))


if __name__ == "__main__":
    main()
