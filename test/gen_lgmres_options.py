#!/usr/bin/env python3
"""Write the pins of the option tests of lgmres and gcrotmk.

The script needs SciPy 1.18.1 and NumPy 2.5.4. It runs them from the
maintainer. The user of the package installs nothing.

The file it writes holds numbers only. For each case it holds the solution,
the count of outer iterations, the vectors that the callback received and
the kept pairs. A kept pair takes 2 n + 1 values: a flag, then two vectors.
The flag is 1.0 when the optional vector exists, and 0.0 when SciPy gives
None. For lgmres the optional vector is the second one (ax). For gcrotmk it
is the first one (c).
"""
import numpy as np
import scipy.sparse as sp
from scipy.sparse.linalg import lgmres, gcrotmk

OUT = "test/suite/lgmres_options_pins.goose"
RTOL = 1e-10


def emit(lines, name, values):
    lines.append(f"const {name}: f64[>..] = [{', '.join(repr(float(v)) for v in values)}];")


def systems():
    n1 = 6
    a1 = sp.diags([-1, 2.5, -1], [-1, 0, 1], shape=(n1, n1), format="csr")
    b1 = np.ones(n1)
    b1b = np.arange(1.0, n1 + 1.0)
    rng = np.random.default_rng(344)
    n2 = 8
    d = np.array([1.0, 10.0, 100.0, 1000.0, 2.0, 20.0, 200.0, 2000.0])
    off = rng.uniform(-0.3, 0.3, (n2, n2)) * d[:, None]
    np.fill_diagonal(off, 0.0)
    a2 = sp.csr_matrix(np.diag(d) + off)
    b2 = rng.uniform(0.5, 1.5, n2)
    n3 = 12
    d3 = np.array([1.0, 3.0, 9.0, 27.0, 81.0, 243.0, 729.0, 2187.0, 6561.0, 19683.0, 59049.0, 177147.0])
    off3 = np.zeros((n3, n3))
    for i in range(n3 - 1):
        off3[i, i + 1] = -0.2 * d3[i + 1]
        off3[i + 1, i] = -0.2 * d3[i + 1]
    a3 = sp.csr_matrix(np.diag(d3) + off3)
    b3 = rng.uniform(0.5, 1.5, n3)
    return a1, b1, b1b, a2, b2, d, a3, b3, d3


def pack_lg(ov):
    out = []
    for dx, ax in ov:
        out += [0.0 if ax is None else 1.0] + list(dx) + ([0.0] * len(dx) if ax is None else list(ax))
    return out


def pack_gk(cu):
    out = []
    for c, u in cu:
        out += [0.0 if c is None else 1.0] + ([0.0] * len(u) if c is None else list(c)) + list(u)
    return out


def run(lines, name, kind, a, b, **kw):
    cb = []
    store = []
    if kind == "lg":
        x, info = lgmres(a, b, rtol=RTOL, callback=lambda v: cb.append(v.copy()), outer_v=store, **kw)
    else:
        x, info = gcrotmk(a, b, rtol=RTOL, callback=lambda v: cb.append(v.copy()), CU=store, **kw)
    emit(lines, name + "_X", x)
    emit(lines, name + "_IT", [info])
    emit(lines, name + "_NCB", [len(cb)])
    emit(lines, name + "_CB", [v for vec in cb for v in vec])
    emit(lines, name + "_NP", [len(store)])
    emit(lines, name + "_P", pack_lg(store) if kind == "lg" else pack_gk(store))
    return store


def main():
    a1, b1, b1b, a2, b2, d, a3, b3, d3 = systems()
    lines = ["// Generated by test/gen_lgmres_options.py. Do not edit by hand.", "",
             "// The pins of the option tests of lgmres and gcrotmk. They come from SciPy 1.18.1.",
             "namespace lgmres_options_pins;", ""]
    emit(lines, "A1", a1.toarray().ravel())
    emit(lines, "B1", b1)
    emit(lines, "B1B", b1b)
    emit(lines, "A2", a2.toarray().ravel())
    emit(lines, "B2", b2)
    emit(lines, "MD2", 1.0 / d)
    emit(lines, "A3", a3.toarray().ravel())
    emit(lines, "B3", b3)
    emit(lines, "MD3", 1.0 / d3)
    pm = sp.diags(1.0 / d)
    lg1 = run(lines, "LG1", "lg", a1, b1)
    run(lines, "LG1_NOAV", "lg", a1, b1, store_outer_Av=False)
    run(lines, "LG1_PRE", "lg", a1, b1, prepend_outer_v=True, inner_m=3)
    run(lines, "LG2", "lg", a2, b2)
    run(lines, "LG2_M", "lg", a2, b2, M=pm)
    gk1 = run(lines, "GK1", "gk", a1, b1)
    run(lines, "GK1_DISC", "gk", a1, b1, discard_C=True)
    run(lines, "GK1_M3", "gk", a1, b1, m=3, k=2)
    run(lines, "GK1_SMALL", "gk", a1, b1, m=3, k=2, truncate="smallest")
    run(lines, "GK2", "gk", a2, b2)
    run(lines, "GK2_M", "gk", a2, b2, M=pm)
    pm3 = sp.diags(1.0 / d3)
    run(lines, "LG3", "lg", a3, b3)
    run(lines, "LG3_M", "lg", a3, b3, M=pm3)
    run(lines, "GK3", "gk", a3, b3)
    run(lines, "GK3_M", "gk", a3, b3, M=pm3)
    # A second solve takes the pairs of the first.
    x, info = lgmres(a1, b1b, rtol=RTOL, outer_v=list(lg1))
    emit(lines, "LG1_2_X", x)
    emit(lines, "LG1_2_IT", [info])
    x, info = gcrotmk(a1, b1b, rtol=RTOL, CU=list(gk1))
    emit(lines, "GK1_2_X", x)
    emit(lines, "GK1_2_IT", [info])
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
