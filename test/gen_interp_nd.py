#!/usr/bin/env python3
"""Write the pins of the tests of the scattered interpolation calls.

The script needs Python 3 with NumPy 2.5.4 and SciPy 1.18.1. It runs
from the directory of the package. The user of the package installs
nothing. The file it writes holds numbers only.

The calls under the pins are rbf, rbf_interpolate, aaa_interpolate and
clough_tocher_interpolate of the package.
"""
import numpy as np
from scipy.interpolate import Rbf, RBFInterpolator, AAA, CloughTocher2DInterpolator

OUT = "test/suite/interp_nd_pins.goose"


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in np.asarray(values).reshape(-1))))


def flat(a):
    return [float(x) for x in np.asarray(a).reshape(-1)]


def main():
    lines = ["// Generated by test/gen_interp_nd.py. Do not edit by hand.", "",
             "// The pins of the tests of the scattered interpolation calls.",
             "// They come from SciPy 1.18.1 and NumPy 2.5.4.",
             "namespace interp_nd_pins;", ""]

    rng = np.random.default_rng(42)
    pts = rng.uniform(-1.0, 1.0, (12, 2))
    vals = np.sin(pts[:, 0] * 2.0) * np.cos(pts[:, 1]) + 0.2 * pts[:, 0]
    query = np.array([[-0.4, 0.3], [0.1, -0.7], [0.5, 0.5], [-0.8, -0.1], [0.2, 0.8]])
    emit(lines, "RBF_PTS", pts.reshape(-1))
    emit(lines, "RBF_VALS", vals)
    emit(lines, "RBF_QUERY", query.reshape(-1))

    # The legacy interpolator of the multiquadric and the default shape.
    rb = Rbf(pts[:, 0], pts[:, 1], vals)
    emit(lines, "RBF_MQ_VALUE", rb(query[:, 0], query[:, 1]))

    # The Gaussian with a shape and a smoothing.
    rb = Rbf(pts[:, 0], pts[:, 1], vals, function="gaussian", epsilon=0.8, smooth=0.1)
    emit(lines, "RBF_GAUSS_VALUE", rb(query[:, 0], query[:, 1]))

    # The thin plate spline of one dimension.
    x1 = np.linspace(-2.0, 2.0, 9)
    v1 = np.exp(-x1 * x1 / 2.0)
    q1 = np.array([-1.7, -0.5, 0.3, 1.4])
    rb = Rbf(x1, v1, function="thin_plate")
    emit(lines, "RBF_TPS_1D_NODES", x1)
    emit(lines, "RBF_TPS_1D_VALS", v1)
    emit(lines, "RBF_TPS_1D_QUERY", q1)
    emit(lines, "RBF_TPS_1D_VALUE", rb(q1))

    # The interpolator of the radial basis with the kernels of SciPy.
    ip = RBFInterpolator(pts, vals)
    emit(lines, "RBFI_TPS_VALUE", ip(query))
    ip = RBFInterpolator(pts, vals, kernel="multiquadric", epsilon=2.0)
    emit(lines, "RBFI_MQ_VALUE", ip(query))
    ip = RBFInterpolator(pts, vals, kernel="linear", degree=0)
    emit(lines, "RBFI_LINEAR_VALUE", ip(query))
    ip = RBFInterpolator(pts, vals, kernel="gaussian", epsilon=1.5, degree=-1)
    emit(lines, "RBFI_GAUSS_VALUE", ip(query))
    ip = RBFInterpolator(pts, vals, smoothing=0.5)
    emit(lines, "RBFI_SMOOTH_VALUE", ip(query))

    # The nearest points of the query bound the system.
    pts20 = rng.uniform(-1.0, 1.0, (24, 2))
    vals20 = np.sin(pts20.sum(axis=1))
    q20 = rng.uniform(-0.9, 0.9, (4, 2))
    ip = RBFInterpolator(pts20, vals20, neighbors=8)
    emit(lines, "RBFI_NB_PTS", pts20.reshape(-1))
    emit(lines, "RBFI_NB_VALS", vals20)
    emit(lines, "RBFI_NB_QUERY", q20.reshape(-1))
    emit(lines, "RBFI_NB_VALUE", ip(q20))

    # One dimension of centers and two columns of values.
    y1 = np.linspace(-1.0, 1.0, 11).reshape(-1, 1)
    d1 = np.sin(3.0 * y1[:, 0])
    ip = RBFInterpolator(y1, d1)
    emit(lines, "RBFI_1D_PTS", y1.reshape(-1))
    emit(lines, "RBFI_1D_VALS", d1)
    emit(lines, "RBFI_1D_QUERY", np.array([[-0.9], [0.05], [0.6]]))
    emit(lines, "RBFI_1D_VALUE", ip(np.array([[-0.9], [0.05], [0.6]])))
    d2 = np.column_stack([np.sin(3.0 * pts[:, 0]), np.cos(2.0 * pts[:, 1])])
    ip = RBFInterpolator(pts, d2)
    emit(lines, "RBFI_MULTI_VALS", d2.reshape(-1))
    emit(lines, "RBFI_MULTI_VALUE", ip(query))

    # The rational approximation of AAA.
    xa = np.linspace(-1.0, 1.0, 100)
    fa = 1.0 / (1.0 + 25.0 * xa * xa)
    qa = np.array([-0.95, -0.4, 0.15, 0.7, 0.99])
    ra = AAA(xa, fa, clean_up=False)
    rc = AAA(xa, fa)
    assert np.allclose(ra(qa), rc(qa), atol=1e-12), "the AAA sample holds a doublet"
    emit(lines, "AAA_RUNGE_X", xa)
    emit(lines, "AAA_RUNGE_F", fa)
    emit(lines, "AAA_RUNGE_QUERY", qa)
    emit(lines, "AAA_RUNGE_VALUE", rc(qa))

    xb = np.linspace(-1.0, 1.0, 200)
    fb = np.exp(-xb * xb) * np.cos(5.0 * xb)
    qb = np.array([-0.8, -0.2, 0.35, 0.85])
    rb_ = AAA(xb, fb, clean_up=False)
    rbc = AAA(xb, fb)
    assert np.allclose(rb_(qb), rbc(qb), atol=1e-12), "the AAA sample holds a doublet"
    emit(lines, "AAA_EXP_X", xb)
    emit(lines, "AAA_EXP_F", fb)
    emit(lines, "AAA_EXP_QUERY", qb)
    emit(lines, "AAA_EXP_VALUE", rbc(qb))
    # A function with a pole outside the sample. The approximation
    # follows the pole without a doublet in the sample.
    xc = np.linspace(0.0, 1.0, 80)
    fc = 1.0 / (xc + 0.2)
    qc = np.array([0.1, 0.5, 0.95])
    ra_ = AAA(xc, fc, clean_up=False)
    rac = AAA(xc, fc)
    assert np.allclose(ra_(qc), rac(qc), atol=1e-12), "the AAA sample holds a doublet"
    emit(lines, "AAA_POLE_X", xc)
    emit(lines, "AAA_POLE_F", fc)
    emit(lines, "AAA_POLE_QUERY", qc)
    emit(lines, "AAA_POLE_VALUE", rac(qc))

    # The Clough-Tocher interpolator of the triangles. The points sit
    # in a disk at random, so no four of them lie on one circle and
    # the hull holds the center of the disk.
    rng2 = np.random.default_rng(7)
    ang = rng2.uniform(0.0, 2.0 * np.pi, 40)
    rad = np.sqrt(rng2.uniform(0.0, 1.0, 40))
    cp = np.column_stack([rad * np.cos(ang), rad * np.sin(ang)])
    cv = np.exp(-cp[:, 0] ** 2 - cp[:, 1] ** 2)
    cq = np.array([[-0.3, -0.15], [0.1, 0.25], [0.35, -0.4],
                   [-0.2, 0.5], [0.45, 0.1], [1.4, 1.4]])
    inside = cq[:5]
    ip = CloughTocher2DInterpolator(cp, cv)
    out = ip(inside)
    assert np.all(np.isfinite(out)), "a point of the query lies outside the hull"
    emit(lines, "CT_PTS", cp.reshape(-1))
    emit(lines, "CT_VALS", cv)
    emit(lines, "CT_QUERY", inside.reshape(-1))
    emit(lines, "CT_VALUE", out)
    # Two columns of values.
    cv2 = np.column_stack([cv, np.sin(3.0 * cp[:, 1])])
    ip = CloughTocher2DInterpolator(cp, cv2)
    emit(lines, "CT_MULTI_VALS", cv2.reshape(-1))
    emit(lines, "CT_MULTI_VALUE", ip(inside))
    # The rescale holds axes of a different width.
    cpr = cp.copy()
    cpr[:, 0] *= 1000.0
    cqr = inside.copy()
    cqr[:, 0] *= 1000.0
    ip = CloughTocher2DInterpolator(cpr, cv, rescale=True)
    emit(lines, "CT_RESCALE_QUERY", cqr.reshape(-1))
    emit(lines, "CT_RESCALE_VALUE", ip(cqr))
    # A point outside the hull takes the fill value.
    emit(lines, "CT_OUT_QUERY", cq[5])

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
