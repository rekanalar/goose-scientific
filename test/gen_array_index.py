#!/usr/bin/env python3
"""Write the pins of the tests of the index helpers.

The script needs NumPy 2.5.4. It runs from the maintainer, from the root
of the package: python -I test/gen_array_index.py. The user of the
package installs nothing.

The file it writes holds numbers only. A set of places holds the row
numbers and then the column numbers. The shape (count, ndim) of a walk is
flat, in row-major order. A path holds one row per step, padded with -1
to the width of the longest step. A count of operations is the
"Optimized FLOP count" of np.einsum_path.
"""
import re
import numpy as np

OUT = "test/suite/array_index_pins.goose"


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" % (name, ", ".join(repr(float(v)) for v in values)))


def flat(pair):
    return [int(v) for part in pair for v in part]


def path_rows(path):
    steps = path[1:]
    width = max(len(s) for s in steps)
    return [v for s in steps for v in list(s) + [-1] * (width - len(s))]


def flops(text):
    return float(re.search(r"Optimized FLOP count:\s+([0-9.e+]+)", text).group(1))


def main():
    lines = ["// Generated by test/gen_array_index.py. Do not edit by hand.", "",
             "// The pins of the tests of the index helpers. They come from NumPy 2.5.4.",
             "namespace array_index_pins;", ""]
    emit(lines, "TRIL_23", flat(np.tril_indices_from(np.zeros((2, 3)))))
    emit(lines, "TRIL_34_K1", flat(np.tril_indices_from(np.zeros((3, 4)), 1)))
    emit(lines, "TRIU_34_K1", flat(np.triu_indices_from(np.zeros((3, 4)), 1)))
    emit(lines, "TRIU_43_KM1", flat(np.triu_indices_from(np.zeros((4, 3)), -1)))
    emit(lines, "MASK_TRIU_4_K1", flat(np.mask_indices(4, np.triu, 1)))
    emit(lines, "MASK_TRIL_3", flat(np.mask_indices(3, np.tril)))
    emit(lines, "DIAG_3_3", flat(np.diag_indices_from(np.zeros((3, 3, 3)))))
    emit(lines, "NDINDEX_232", [v for ix in np.ndindex(2, 3, 2) for v in ix])
    a = np.arange(6.0).reshape(2, 3) + 5.0
    emit(lines, "ENUM_VALUES", [v for _, v in np.ndenumerate(a)])
    emit(lines, "ENUM_PLACES", [i for ix, _ in np.ndenumerate(a) for i in ix])
    cases = [
        ("EP_IJ_JK", "ij,jk->ik", [(2, 3), (3, 4)]),
        ("EP_CHAIN_A", "ij,jk,kl->il", [(2, 3), (3, 4), (4, 5)]),
        ("EP_CHAIN_B", "ij,jk,kl->il", [(2, 2), (2, 5), (5, 2)]),
        ("EP_TRACE", "ii->", [(3, 3)]),
        ("EP_OUTER", "i,j,k->ijk", [(2,), (3,), (4,)]),
        ("EP_STAR", "ab,bc,cd,de->ae", [(2, 3), (3, 4), (4, 5), (5, 2)]),
    ]
    for name, spec, shapes in cases:
        path, text = np.einsum_path(spec, *[np.zeros(s) for s in shapes])
        emit(lines, name + "_PATH", path_rows(path))
        emit(lines, name + "_FLOPS", [flops(text)])
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
