#!/usr/bin/env python3
"""Write the pins of the tests of the business days and the dates.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. A date is a count of days since
1970-01-01, as an f64 value. A date that is not a time is the code 1 in
the NAT lists, and the day number 0 in the day lists. A text result is
a run of byte values, and a span list holds the start and the length of
each text. A length of -1 means that NumPy raised an error for the case.
The code -999999999 marks a case where NumPy raised an error.

Each case that uses a calendar holds a code for the calendar in the
CAL lists. The hand-written test holds the mask and the holidays of
each code. The codes are:
0 the default calendar (Monday to Friday, no holiday)
1 the mask 1111110 and the holiday 2026-12-25
2 the mask 1100011 and the holidays 2026-12-25 and 2026-01-01
3 the mask SatSun and no holiday
4 the mask Sun TueWed  Thu Fri and no holiday
"""
import random
import datetime
import warnings

import numpy as np

warnings.simplefilter('ignore')
OUT = "test/suite/array_busday_pins.goose"

EPOCH = datetime.date(1970, 1, 1)
ERR = -999999999


def day(text):
    return (datetime.date.fromisoformat(str(text)) - EPOCH).days


CAL_MASKS = ["1111100", "1111110", "1100011", "SatSun", "Sun TueWed  Thu Fri"]
# Holidays per calendar code, as day numbers. Code 0 and 3 and 4 hold none.
CAL_HOLIDAYS = [[], [day("2026-12-25")], [day("2026-12-25"), day("2026-01-01")], [], []]


def rows(name, values):
    return "const %s: f64[>..] = [%s];" % (name, ", ".join(repr(float(v)) for v in values))


class Texts:
    def __init__(self):
        self.bytes = []
        self.spans = []

    def add(self, s):
        if s is None:
            self.spans += [0, -1]
            return
        self.spans += [len(self.bytes), len(s)]
        self.bytes += [ord(c) for c in s]


def main():
    lines = ["// Generated by test/gen_array_busday.py. Do not edit by hand.", "",
             "// The pins of the tests of the business days and the dates.",
             "// They come from NumPy 2.5.4.",
             "namespace array_busday_pins;", ""]
    rnd = random.Random(363)

    # The counts. Each case: cal code, begin day, end day, count.
    # The code ERR marks a case where NumPy raised an error.
    count_rows = []
    pairs = [
        ("2026-01-01", "2026-01-31"), ("2026-11-14", "2026-12-25"),
        ("2026-01-31", "2026-01-01"), ("2026-11-16", "2026-11-16"),
        ("2026-11-15", "2026-11-16"), ("2026-11-16", "2026-11-15"),
        ("2026-11-14", "2026-11-15"), ("2026-11-15", "2026-11-21"),
        ("2026-11-20", "2026-11-14"), ("2026-01-01", "2027-01-01"),
        ("0001-01-01", "9999-12-31"), ("1999-12-31", "2000-01-03"),
        ("2026-11-13", "2026-11-14"), ("2026-11-14", "2026-11-16"),
        ("2024-02-28", "2024-03-01"), ("2023-02-28", "2023-03-01"),
        ("2026-12-24", "2026-12-28"), ("2026-12-25", "2026-12-28"),
    ]
    for cal in range(5):
        for a, b in pairs:
            try:
                c = np.busday_count(a, b, weekmask=CAL_MASKS[cal],
                                    holidays=[str(EPOCH + datetime.timedelta(days=h)) for h in CAL_HOLIDAYS[cal]])
            except (ValueError, TypeError):
                c = ERR
            count_rows += [cal, day(a), day(b), c]
    for _ in range(200):
        cal = rnd.choice([0, 1, 2, 3, 4])
        a = day(EPOCH + datetime.timedelta(days=rnd.randint(-700000, 2500000)))
        b = a + rnd.randint(-4000, 4000)
        try:
            c = np.busday_count(EPOCH + datetime.timedelta(days=a),
                                EPOCH + datetime.timedelta(days=b),
                                weekmask=CAL_MASKS[cal],
                                holidays=[str(EPOCH + datetime.timedelta(days=h)) for h in CAL_HOLIDAYS[cal]])
        except (ValueError, TypeError):
            c = ERR
        count_rows += [cal, a, b, c]
    lines.append("// COUNT: cal code, begin day, end day, count (ERR is an error)")
    lines.append(rows("COUNT", count_rows))

    # The offsets. Each case: cal code, roll code, day, offset, nat flag,
    # result day. A result of ERR means that NumPy raised an error.
    ROLLS = ["raise", "nat", "forward", "following", "backward", "preceding",
             "modifiedfollowing", "modifiedpreceding"]
    offset_rows = []
    offset_nat = []
    fixed = [
        ("2026-11-13", 3), ("2026-11-13", -3), ("2026-11-14", 0),
        ("2026-11-14", 1), ("2026-11-14", -1), ("2026-11-16", 0),
        ("2026-12-25", 0), ("2026-12-25", 1), ("2026-12-25", -1),
        ("2026-11-30", 1), ("2026-11-30", -1), ("2026-12-31", 1),
        ("2027-01-01", -1), ("2026-02-28", 1), ("2026-03-01", -1),
        ("2026-11-13", 100), ("2026-11-13", -100), ("2026-11-13", 365),
    ]
    for cal in [0, 1, 2, 3, 4]:
        for d, o in fixed:
            for roll in ROLLS:
                try:
                    r = np.busday_offset(d, o, roll=roll, weekmask=CAL_MASKS[cal],
                                         holidays=[str(EPOCH + datetime.timedelta(days=h)) for h in CAL_HOLIDAYS[cal]])
                    nat = 0
                    if np.isnat(r):
                        nat = 1
                        r = 0
                    else:
                        r = day(r)
                except (ValueError, TypeError):
                    r, nat = ERR, 0
                offset_rows += [cal, ROLLS.index(roll), day(d), o, nat, r]
    for _ in range(300):
        cal = rnd.choice([0, 1, 2, 3, 4])
        d = day(EPOCH + datetime.timedelta(days=rnd.randint(-700000, 2500000)))
        o = rnd.choice([-40, -10, -7, -3, -2, -1, 0, 1, 2, 3, 7, 10, 40, 365])
        roll = rnd.choice(ROLLS)
        try:
            r = np.busday_offset(EPOCH + datetime.timedelta(days=d), o, roll=roll,
                                 weekmask=CAL_MASKS[cal],
                                 holidays=[str(EPOCH + datetime.timedelta(days=h)) for h in CAL_HOLIDAYS[cal]])
            nat = 0
            if np.isnat(r):
                nat = 1
                r = 0
            else:
                r = day(r)
        except (ValueError, TypeError):
            r, nat = ERR, 0
        offset_rows += [cal, ROLLS.index(roll), d, o, nat, r]
    lines.append("// OFFSET: cal code, roll code, day, offset, nat flag, result day (ERR is an error)")
    lines.append(rows("OFFSET", offset_rows))

    # is_busday. Each case: cal code, day, nat flag, flag.
    is_rows = []
    tests = ["2026-11-14", "2026-11-15", "2026-11-16", "2026-12-25",
             "2026-01-01", "2026-01-03", "2026-01-04", "0001-01-01",
             "9999-12-31", "2024-02-29", "2100-02-28"]
    for cal in range(5):
        for t in tests:
            v = np.is_busday(t, weekmask=CAL_MASKS[cal],
                             holidays=[str(EPOCH + datetime.timedelta(days=h)) for h in CAL_HOLIDAYS[cal]])
            is_rows += [cal, day(t), 0, 1 if v else 0]
    is_rows += [0, 0, 1, 0]  # a date that is not a time is no business day
    lines.append("// ISBUSDAY: cal code, day, nat flag, flag")
    lines.append(rows("ISBUSDAY", is_rows))

    # isnat. Each case: day, nat flag. A day of ERR stands for a date
    # that is not a time.
    nat_rows = []
    for t in ["2026-11-14", "1970-01-01", "0001-01-01"]:
        nat_rows += [day(t), 0]
    nat_rows += [ERR, 1]
    lines.append("// ISNAT: day (ERR stands for a date that is not a time), nat flag")
    lines.append(rows("ISNAT", nat_rows))

    # busdaycalendar. Each case: cal code, and the mask bytes and the
    # holiday days of the calendar that NumPy holds.
    cal_rows = []
    cal_bytes, cal_spans = Texts(), Texts()
    cal_hol = []
    for cal in range(5):
        b = np.busdaycalendar(weekmask=CAL_MASKS[cal],
                              holidays=[str(EPOCH + datetime.timedelta(days=h)) for h in CAL_HOLIDAYS[cal]])
        mask = "".join(str(int(x)) for x in b.weekmask)
        cal_bytes.add(mask)
        cal_spans.add(mask)
        cal_hol.append([day(str(h)) for h in b.holidays])
        cal_rows.append(cal)
    lines.append("// CAL: one row per calendar code")
    lines.append(rows("CAL", cal_rows))
    lines.append(rows("CAL_BYTES", cal_bytes.bytes))
    lines.append(rows("CAL_SPANS", cal_spans.spans))
    flat = []
    for hol in cal_hol:
        flat += [len(hol)] + hol
    lines.append("// CAL_HOL: per calendar, the count of the holidays, then the days")
    lines.append(rows("CAL_HOL", flat))

    # datetime_as_string. Each case: day, text. A span of -1 is an error.
    t_texts = Texts()
    t_rows = []
    texts = ["2026-11-14", "2026-11-15", "0001-01-01", "9999-12-31",
             "1970-01-01", "2024-02-29", "2000-02-29", "1900-02-28"]
    for t in texts:
        t_rows.append(day(t))
        t_texts.add(t)
    t_rows.append(ERR)
    t_texts.add("NaT")
    lines.append("// TEXT: day (the last row stands for NaT), then the bytes and the spans")
    lines.append(rows("TEXT_DATE", t_rows))
    lines.append(rows("TEXT_BYTES", t_texts.bytes))
    lines.append(rows("TEXT_SPANS", t_texts.spans))

    # datetime_data. Each case: spec code, unit code, count. A unit code
    # of -1 means that NumPy raised an error. The unit names live in the
    # hand-written test, in the order of this list.
    UNIT_NAMES = ["Y", "M", "W", "D", "h", "m", "s", "ms", "us", "ns", "ps",
                  "fs", "as", "generic"]
    specs = ["M8[D]", "M8[s]", "M8[ms]", "M8[5ms]", "M8[10D]", "M8[Y]",
             "M8[W]", "M8[us]", "M8[ns]", "m8[2W]", "datetime64[7s]",
             "timedelta64[3as]", "M8", "m8", "datetime64", "timedelta64",
             "M8[]", "M8[ms/1000]", "M8[13]", "M8[xx]", "i8", "M8[5us]",
             "M8[10000000000ms]"]
    data_rows = []
    for spec in specs:
        try:
            unit, count = np.datetime_data(spec)
            code = UNIT_NAMES.index(unit)
        except (ValueError, TypeError):
            code, count = -1, 0
        data_rows += [code, count]
    lines.append("// DATA: pairs of unit code (-1 is an error) and count, in the order of the specs")
    lines.append(rows("DATA", data_rows))

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
