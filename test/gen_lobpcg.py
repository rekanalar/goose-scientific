#!/usr/bin/env python3
"""Write the pins of the lobpcg tests.

The script needs SciPy 1.18.1 and NumPy 2.5.4. It runs them from the
maintainer. The user of the package installs nothing.

The file it writes holds numbers only. It holds the entries of each
matrix, the start blocks, the constraint blocks and the values of SciPy.
"""
import numpy as np
import scipy.sparse as sp
from scipy.sparse.linalg import lobpcg

OUT = "test/suite/lobpcg_pins.goose"
TOL = 1.0e-10
MAXITER = 500


def chain(n):
    return sp.diags([-1.0, 2.0, -1.0], [-1, 0, 1], shape=(n, n)).tocsr()


def start(n, k, seed):
    rng = np.random.default_rng(seed)
    return rng.normal(size=(n, k))


def triplets(a):
    coo = a.tocoo()
    order = np.lexsort((coo.col, coo.row))
    return coo.row[order].astype(float), coo.col[order].astype(float), coo.data[order]


def block(x):
    return x.ravel()


def emit(lines, name, values):
    lines.append(f"const {name}: f64[>..] = [{', '.join(repr(float(v)) for v in values)}];")


def main():
    lines = []
    n = 120
    k = 3
    a = chain(n)
    ri, ci, va = triplets(a)
    x = start(n, k, 7)
    xb = block(x)

    # The standard problem. The values come in both orders.
    wsmall, vsmall = lobpcg(a, x, largest=False, tol=TOL, maxiter=MAXITER)
    wlarge, vlarge = lobpcg(a, x, largest=True, tol=TOL, maxiter=MAXITER)
    exact = 2.0 - 2.0 * np.cos(np.arange(1, 4) * np.pi / (n + 1))

    # The generalized problem with a diagonal B.
    b = sp.diags(np.linspace(1.0, 2.0, n)).tocsr()
    ri_b, ci_b, va_b = triplets(b)
    wgen, vgen = lobpcg(a, x, B=b, largest=False, tol=TOL, maxiter=MAXITER)

    # The preconditioner M, the inverse of the diagonal of A.
    m = sp.diags(1.0 / 2.0 * np.ones(n)).tocsr()
    ri_m, ci_m, va_m = triplets(m)
    wpre, vpre = lobpcg(a, x, M=m, largest=False, tol=TOL, maxiter=MAXITER)

    # A diagonal matrix of side 60. The values are exact.
    d = sp.diags(np.arange(1.0, 61.0)).tocsr()
    ri_d, ci_d, va_d = triplets(d)
    xd = start(60, 3, 11)
    wdiag, vdiag = lobpcg(d, xd, largest=False, tol=TOL, maxiter=MAXITER)

    # The constraints Y hold the first two unit vectors, so the values of the
    # rest are known.
    y = np.zeros((60, 2))
    y[0, 0] = 1.0
    y[1, 1] = 1.0
    wcon, vcon = lobpcg(d, xd, Y=y, largest=False, tol=TOL, maxiter=MAXITER)

    lines.append("// Generated by test/gen_lobpcg.py. Do not edit by hand.")
    lines.append("")
    lines.append("// The pins of the lobpcg tests. They come from SciPy 1.18.1.")
    lines.append("namespace lobpcg_pins;")
    lines.append("")
    lines.append("// The chain matrix of side 120.")
    emit(lines, "CHAIN_RI", ri)
    emit(lines, "CHAIN_CI", ci)
    emit(lines, "CHAIN_VA", va)
    emit(lines, "CHAIN_X", xb)
    lines.append("")
    lines.append("// The diagonal matrix of side 60.")
    emit(lines, "DIAG_RI", ri_d)
    emit(lines, "DIAG_CI", ci_d)
    emit(lines, "DIAG_VA", va_d)
    emit(lines, "DIAG_X", block(xd))
    lines.append("")
    lines.append("// The diagonal matrix B of the generalized problem.")
    emit(lines, "BDIAG_RI", ri_b)
    emit(lines, "BDIAG_CI", ci_b)
    emit(lines, "BDIAG_VA", va_b)
    lines.append("")
    lines.append("// The preconditioner M.")
    emit(lines, "M_RI", ri_m)
    emit(lines, "M_CI", ci_m)
    emit(lines, "M_VA", va_m)
    lines.append("")
    lines.append("// The constraints Y.")
    emit(lines, "Y", block(y))
    lines.append("")
    lines.append("// The values of SciPy.")
    emit(lines, "W_SMALL", wsmall)
    emit(lines, "W_LARGE", wlarge)
    emit(lines, "W_EXACT", exact)
    emit(lines, "W_GEN", wgen)
    emit(lines, "W_PRE", wpre)
    emit(lines, "W_CON", wcon)
    emit(lines, "W_DIAG", wdiag)
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
