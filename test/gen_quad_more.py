"""Writes test/suite/quad_more_pins.goose: the pins of newton_cotes, nsum and tanhsinh.

Needs: Python 3, NumPy and SciPy 1.18.1.
Run: /home/ubuntu/works/goose/tmp/venv/bin/python -I test/gen_quad_more.py
"""
import os
import numpy as np
from scipy.integrate import newton_cotes, nsum, tanhsinh

HERE = os.path.dirname(os.path.abspath(__file__))


def arr(name, vals):
    body = ", ".join(repr(float(v)) for v in vals)
    return f"const {name}: f64[{len(vals)}] = [{body}];\n"


out = ["// Generated by test/gen_quad_more.py. Do not edit by hand.\n",
       "// The pins of newton_cotes, nsum and tanhsinh. The values come from SciPy 1.18.1.\n",
       "namespace quad_more_pins;\n\n"]
for n in (1, 2, 4, 6, 8, 14, 16, 20):
    an, b = newton_cotes(n, 1)
    out.append(arr(f"NC{n}", an))
    out.append(arr(f"NC{n}_B", [b]))
out.append(arr("ZETA2", [np.pi ** 2 / 6]))
out.append(arr("ALT_LOG2", [np.log(2)]))
t = tanhsinh(lambda x: np.exp(x) * np.sin(x), 0.0, 2.0, rtol=1e-12).integral
out.append(arr("TS_EXPSIN", [t]))
t = tanhsinh(lambda x: 1 / np.sqrt(x), 0.0, 1.0).integral
out.append(arr("TS_SQRT", [t]))
with open(os.path.join(HERE, "suite", "quad_more_pins.goose"), "w") as f:
    f.writelines(out)
