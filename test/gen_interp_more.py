#!/usr/bin/env python3
"""Write the pins of the tests of the extra interpolation calls.

The script needs SciPy 1.18.1 and NumPy 2.5.4. It runs from the
maintainer. The user of the package installs nothing.

The file it writes holds numbers only.
"""
import numpy as np
from scipy.interpolate import (BarycentricInterpolator, KroghInterpolator,
                               FloaterHormannInterpolator, lagrange, pade,
                               approximate_taylor_polynomial, splrep, spalde,
                               splint, splder, splantider, sproot,
                               make_lsq_spline, RectBivariateSpline, BSpline,
                               pchip_interpolate)

OUT = "test/suite/interp_more_pins.goose"


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in values)))


def flat(a):
    return [float(x) for x in np.asarray(a).reshape(-1)]


def main():
    lines = ["// Generated by test/gen_interp_more.py. Do not edit by hand.", "",
             "// The pins of the tests of the extra interpolation calls.",
             "// They come from SciPy 1.18.1 and NumPy 2.5.4.",
             "namespace interp_more_pins;", ""]

    # The barycentric interpolator.
    xi = np.array([0.0, 1.0, 2.0, 3.0])
    yi = np.array([1.0, 2.0, 0.5, 3.0])
    xq = np.array([-0.3, 0.7, 1.0, 2.4])
    B = BarycentricInterpolator(xi, yi)
    emit(lines, "BARY_NODES", flat(xi))
    emit(lines, "BARY_VALUES", flat(yi))
    emit(lines, "BARY_QUERY", flat(xq))
    emit(lines, "BARY_VALUE", flat(B(xq)))
    emit(lines, "BARY_DER1", flat(B.derivative(xq, 1)))
    emit(lines, "BARY_DER2", flat(B.derivative(xq, 2)))

    emit(lines, "PCHIP_VALUE", flat(pchip_interpolate(xi, yi, xq)))

    # The interpolator of Krogh, with a node that repeats.
    kx = np.array([0.0, 0.0, 1.0, 2.0])
    ky = np.array([0.0, 2.0, 0.0, 4.0])
    kq = np.array([-0.3, 0.7, 1.5])
    K = KroghInterpolator(kx, ky)
    emit(lines, "KROGH_NODES", flat(kx))
    emit(lines, "KROGH_VALUES", flat(ky))
    emit(lines, "KROGH_QUERY", flat(kq))
    emit(lines, "KROGH_VALUE", flat(K(kq)))
    emit(lines, "KROGH_DER1", flat(K.derivative(kq, 1)))
    emit(lines, "KROGH_DER2", flat(K.derivative(kq, 2)))

    # The interpolator of Floater and Hormann.
    fx = np.array([0.0, 1.0, 2.0, 3.0])
    fy = np.array([1.0, 2.0, 0.5, 3.0])
    fq = np.array([-0.3, 0.7, 1.0, 2.4])
    for d in (0, 1, 3):
        F = FloaterHormannInterpolator(fx, fy, d=d)
        emit(lines, "FH_D%d_VALUE" % d, flat(F(fq)))

    # The polynomial of Lagrange.
    lx = np.array([0.0, 1.0, 2.0])
    ly = np.array([1.0, 3.0, 2.0])
    emit(lines, "LAG_NODES", flat(lx))
    emit(lines, "LAG_VALUES", flat(ly))
    emit(lines, "LAG_COEF", flat(lagrange(lx, ly).coef))

    # The approximation of Pade.
    an = np.array([1.0, 1.0, 0.5, 1.0 / 6.0, 1.0 / 24.0, 1.0 / 120.0])
    emit(lines, "PADE_COEFF", flat(an))
    for m, n in ((2, 2), (1, 2), (3, 1)):
        p, q = pade(an, m, n)
        emit(lines, "PADE_%d_%d_P" % (m, n), flat(p.coef))
        emit(lines, "PADE_%d_%d_Q" % (m, n), flat(q.coef))

    # The Taylor polynomial of the function.
    T = approximate_taylor_polynomial(np.exp, 0.5, 3, 1.0)
    emit(lines, "TAYLOR_COEF", flat(T.coef))

    # The algebra of the spline.
    sx = np.linspace(0.0, 3.0, 11)
    sy = np.sin(sx)
    tck = splrep(sx, sy, k=3)
    t, c, k = tck
    emit(lines, "SPL_X", flat(sx))
    emit(lines, "SPL_Y", flat(sy))
    emit(lines, "SPL_KNOTS", flat(t))
    emit(lines, "SPL_COEFS", flat(c))
    sq = np.array([0.5, 1.3, 2.5])
    emit(lines, "SPL_QUERY", flat(sq))
    emit(lines, "SPL_VALUES", flat(BSpline(t, c, k)(sq)))
    emit(lines, "SPL_DER1", flat(BSpline(t, c, k).derivative()(sq)))
    emit(lines, "SPL_INT", [float(splint(0.5, 2.5, tck))])
    emit(lines, "SPL_SPALDE", flat(spalde(sq, tck)))
    d1 = splder(tck, 1)
    emit(lines, "SPLDER_KNOTS", flat(d1[0]))
    emit(lines, "SPLDER_COEFS", flat(d1[1]))
    a1 = splantider(tck, 1)
    emit(lines, "SPLANTI_KNOTS", flat(a1[0]))
    emit(lines, "SPLANTI_COEFS", flat(a1[1]))
    emit(lines, "SPL_ROOT", flat(sproot(tck)))

    # The fit with least squares.
    lx2 = np.linspace(0.0, 3.0, 20)
    ly2 = np.sin(lx2) + 0.1 * np.cos(3.0 * lx2)
    lw = np.ones(20)
    lw[3] = 0.5
    lw[9] = 2.0
    lt = np.r_[[lx2[0]] * 4, [0.5, 1.5, 2.5], [lx2[-1]] * 4]
    L = make_lsq_spline(lx2, ly2, lt, k=3, w=lw)
    emit(lines, "LSQ_X", flat(lx2))
    emit(lines, "LSQ_Y", flat(ly2))
    emit(lines, "LSQ_W", flat(lw))
    emit(lines, "LSQ_KNOTS", flat(lt))
    emit(lines, "LSQ_COEFS", flat(L.c))

    # The spline of two variables on a grid.
    gx = np.linspace(0.0, 1.0, 5)
    gy = np.linspace(0.0, 2.0, 6)
    rng = np.random.default_rng(7)
    gz = rng.random((5, 6))
    G = RectBivariateSpline(gx, gy, gz, kx=3, ky=3, s=0)
    emit(lines, "GRID_X", flat(gx))
    emit(lines, "GRID_Y", flat(gy))
    emit(lines, "GRID_Z", flat(gz))
    emit(lines, "GRID_KNOTS_X", flat(G.get_knots()[0]))
    emit(lines, "GRID_KNOTS_Y", flat(G.get_knots()[1]))
    qx = np.array([0.3, 0.9])
    qy = np.array([0.7, 1.9])
    emit(lines, "GRID_QUERY_X", flat(qx))
    emit(lines, "GRID_QUERY_Y", flat(qy))
    grid = G(qx, qy)
    emit(lines, "GRID_VALUE", flat(grid))
    emit(lines, "GRID_DX", flat(G(qx, qy, dx=1)))
    emit(lines, "GRID_DY", flat(G(qx, qy, dy=1)))

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT, "with", len(lines) - 5, "lists")


main()
