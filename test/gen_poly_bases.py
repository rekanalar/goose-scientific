#!/usr/bin/env python3
"""Write the pins of the tests of the five orthogonal polynomial bases.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. Ragged lists are two buffers: the
values joined end to end, and the length of each part. For each family
(LEG, CHEB, HERM, HERME, LAG) it holds the value of each series at each
point, both conversions of each series, the derivatives and the integrals
of each series for a list of option sets, and the roots of a second list
of series.
"""
import numpy as np
from numpy.polynomial import legendre, chebyshev, hermite, hermite_e, laguerre

OUT = "test/suite/poly_bases_pins.goose"
FAMS = [("LEG", legendre, "leg", "leggauss"), ("CHEB", chebyshev, "cheb", "chebgauss"),
        ("HERM", hermite, "herm", "hermgauss"), ("HERME", hermite_e, "herme", "hermegauss"),
        ("LAG", laguerre, "lag", "laggauss")]
# The series of the value, conversion, derivative and integral tests.
DEGREES = [0, 1, 2, 3, 4, 5, 6, 8, 10, 12, 14, 1, 2, 3, 5, 7, 9, 11, 13, 15]
POINTS = [-1.3, -0.5, 0.0, 0.37, 1.0, 2.2]
# The option sets of the derivative: (m, scl).
DER_CASES = [(0, 1.0), (1, 1.0), (2, 1.0), (3, 0.7), (1, -2.5)]
# The option sets of the integral: (m, k, lbnd, scl).
INT_CASES = [(0, [], 0.0, 1.0), (1, [], 0.0, 1.0), (1, [0.5], 0.3, 1.0),
             (2, [0.2, -1.1], -0.4, 1.3), (3, [], 0.0, 0.8), (2, [1.5], 1.0, 1.0)]
ROOT_DEGREES = list(range(1, 21)) + [3, 4, 5, 6, 7, 8]


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" % (name, ", ".join(repr(float(v)) for v in values)))


def ragged(lines, name, parts):
    flat = [v for p in parts for v in p]
    emit(lines, name + "_D", flat)
    emit(lines, name + "_L", [len(p) for p in parts])


def main():
    rng = np.random.default_rng(345)
    series = [rng.normal(size=d + 1) for d in DEGREES]
    roots_in = [rng.normal(size=d + 1) for d in ROOT_DEGREES]
    lines = ["// Generated by test/gen_poly_bases.py. Do not edit by hand.", "",
             "// The pins of the tests of the orthogonal polynomial bases. They come from NumPy 2.5.4.",
             "namespace poly_bases_pins;", ""]
    ragged(lines, "S", series)
    emit(lines, "X", POINTS)
    ragged(lines, "R", roots_in)
    emit(lines, "DER_M", [m for m, _ in DER_CASES])
    emit(lines, "DER_S", [s for _, s in DER_CASES])
    emit(lines, "INT_M", [m for m, _, _, _ in INT_CASES])
    emit(lines, "INT_LB", [lb for _, _, lb, _ in INT_CASES])
    emit(lines, "INT_S", [s for _, _, _, s in INT_CASES])
    ragged(lines, "INT_K", [k for _, k, _, _ in INT_CASES])
    for code, mod, p, gauss in FAMS:
        val = getattr(mod, p + "val")
        # The roots of the basis polynomial of degree 20 are the Gauss nodes.
        emit(lines, code + "_B20", sorted(getattr(mod, gauss)(20)[0]))
        emit(lines, code + "_VAL", [val(x, c) for c in series for x in POINTS])
        ragged(lines, code + "_TOM", [getattr(mod, p + "2poly")(c) for c in series])
        ragged(lines, code + "_FRM", [getattr(mod, "poly2" + p)(c) for c in series])
        ragged(lines, code + "_DER", [getattr(mod, p + "der")(c, m, s) for m, s in DER_CASES for c in series])
        ragged(lines, code + "_INT", [getattr(mod, p + "int")(c, m, k, lb, s)
                                      for m, k, lb, s in INT_CASES for c in series])
        rts = [getattr(mod, p + "roots")(c) for c in roots_in]
        ragged(lines, code + "_RE", [np.real(r) for r in rts])
        ragged(lines, code + "_IM", [np.imag(r) for r in rts])
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


main()
