#!/usr/bin/env python3
"""Write test/suite/tridiag_blocks_pins.goose, the pins of eigh_tridiagonal.

The file holds the matrices and the eigenvalues of SciPy 1.18.1 and NumPy
2.5.4 for the tests of the group tridiag_blocks. It holds numbers only.

Needs Python 3.11 or later, SciPy 1.18.1 and NumPy 2.5.4.

   tmp/venv/bin/python -I test/gen_tridiag_blocks.py
"""
import numpy as np
from scipy.linalg import eigvalsh_tridiagonal

OUT = 'test/suite/tridiag_blocks_pins.goose'


def lst(xs):
    return "[" + ", ".join(repr(float(x)) for x in xs) + "]"


def block_matrix(rng, sizes):
    """A matrix of blocks. Diagonal values repeat across the blocks."""
    d = rng.choice([1.0, 2.0, 3.0, 4.0], sum(sizes))
    e = []
    for s_i, s in enumerate(sizes):
        e += list(rng.uniform(0.5, 1.5, s - 1))
        if s_i < len(sizes) - 1:
            e.append(0.0)
    return d, np.array(e)


rng = np.random.default_rng(340)
cases = {
    'M1': (np.array([1.0, 1, 1, 5]), np.zeros(3)),
    'M2': (np.array([2.0, 2, 2, 2]), np.array([0.0, 1e-20, 0.0])),
    'M3': (np.array([1.0, 1, 1]), np.array([1e-20, 1e-20])),
    'M4': (np.array([3.0, 1, 1, 3]), np.zeros(3)),
    'M5': block_matrix(rng, [3, 1, 4, 2, 5]),
    'M6': (rng.uniform(-2, 2, 40), rng.uniform(0.3, 1.5, 39)),
    # A large value beside two tiny ones. The coupling of the tiny ones
    # must stay, because a large value elsewhere must not hide it.
    'M7': (np.array([1.0e10, 1.0e-10, 1.0e-10]), np.array([1.0e-6, 1.0e-6])),
    # A coupling that is negligible against its own place.
    'M8': (np.array([1.0, 1.0, 1.0, 5.0]), np.array([0.0, 1.0e-20, 0.0])),
}
lines = ["// Generated by test/gen_tridiag_blocks.py. Do not edit by hand.",
         "namespace tridiag_blocks_pins;", ""]
for name, (d, e) in cases.items():
    w = eigvalsh_tridiagonal(d, e)
    for tag, v in (('D', d), ('E', e), ('W', w)):
        lines.append("const %s_%s: f64[%d] = %s;" % (tag, name, len(v), lst(v)))
open(OUT, 'w').write("\n".join(lines) + "\n")
