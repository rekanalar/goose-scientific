#!/usr/bin/env python3
"""Write the pins of the tests of the civil calendar of the dates.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing. Run it from the package directory:
  python3 -I test/gen_date_civil.py

The file it writes holds numbers only. A date is a count of days since
1970-01-01. NumPy gives each number: the day of a date text comes from
np.datetime64, the year and the month come from the units Y and M, and
the day of the week comes from np.is_busday with a weekmask of one day.
The week starts at Monday, so Monday is 0.

The lists:
DAYS     year, month, day, count of days (years 1 to 9999)
PARTS    count of days, year, month, day, day of the week
OUTSIDE  year, month, day, count of days (years outside 1 to 9999)
BAD      year, month, day of a date that NumPy refuses
"""
import random
import warnings

import numpy as np

warnings.simplefilter('ignore')
OUT = "test/suite/date_civil_pins.goose"
MASKS = ["1000000", "0100000", "0010000", "0001000", "0000100", "0000010",
         "0000001"]


def days_of(y, m, d):
    return int(np.datetime64("%04d-%02d-%02d" % (y, m, d), "D").astype("int64"))


def parts_of(days):
    t = np.datetime64(int(days), "D")
    y = int(t.astype("M8[Y]").astype("int64")) + 1970
    m = int(t.astype("M8[M]").astype("int64")) % 12 + 1
    d = int((t - t.astype("M8[M]")).astype("int64")) + 1
    wd = [i for i in range(7) if np.is_busday(t, weekmask=MASKS[i])][0]
    return y, m, d, wd


def rows(name, values):
    return "const %s: f64[>..] = [%s];" % (name, ", ".join(repr(float(v)) for v in values))


def main():
    rnd = random.Random(364)
    fixed = [
        (1, 1, 1), (9999, 12, 31), (1970, 1, 1), (1969, 12, 31),
        (2000, 2, 29), (1900, 2, 28), (1900, 3, 1), (2100, 2, 28),
        (2100, 3, 1), (2024, 2, 29), (2023, 2, 28), (2023, 3, 1),
        (2026, 11, 14), (2026, 12, 31), (2027, 1, 1), (1, 2, 28),
        (1, 3, 1), (400, 2, 29), (100, 2, 28), (9999, 1, 1),
        (1582, 10, 4), (1582, 10, 15), (4, 2, 29), (2000, 1, 1),
    ]
    triples = list(fixed)
    for _ in range(400):
        y = rnd.randint(1, 9999)
        m = rnd.randint(1, 12)
        last = 31
        if m in (4, 6, 9, 11):
            last = 30
        if m == 2:
            leap = y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)
            last = 29 if leap else 28
        triples.append((y, m, rnd.randint(1, last)))
    day_rows = []
    for y, m, d in triples:
        day_rows += [y, m, d, days_of(y, m, d)]

    # Each day of the fixed dates, the two ends of the range, and
    # random days: the parts of the day and the day of the week.
    part_days = [days_of(*t) for t in fixed]
    part_days += [-719162, 2932896]
    part_days += [rnd.randint(-719162, 2932896) for _ in range(400)]
    part_rows = []
    for dd in part_days:
        y, m, d, wd = parts_of(dd)
        part_rows += [dd, y, m, d, wd]

    # Dates outside the years 1 to 9999. The algorithm holds for them.
    outside = [(0, 1, 1), (0, 2, 29), (0, 3, 1), (-1, 12, 31), (-4, 2, 29),
               (-400, 3, 1), (10000, 1, 1), (10000, 2, 29), (12345, 6, 7),
               (-1000, 1, 1), (99999, 12, 31)]
    out_rows = []
    for y, m, d in outside:
        out_rows += [y, m, d, days_of(y, m, d)]

    # Dates that NumPy refuses.
    bad = [(1900, 2, 29), (2026, 2, 30), (2026, 4, 31), (2026, 13, 1),
           (2026, 0, 1), (2026, 1, 0), (2026, 1, 32), (2023, 2, 29),
           (2100, 2, 29), (2026, 6, 31), (2026, 9, 31), (2026, 11, 31)]
    bad_rows = []
    for y, m, d in bad:
        try:
            days_of(y, m, d)
        except ValueError:
            bad_rows += [y, m, d]
        else:
            raise SystemExit("NumPy accepts %r" % ((y, m, d),))

    lines = ["// Generated by test/gen_date_civil.py. Do not edit by hand.", "",
             "// The pins of the tests of the civil calendar of the dates.",
             "// They come from NumPy 2.5.4.",
             "namespace date_civil_pins;", "",
             "// DAYS: year, month, day, count of days", rows("DAYS", day_rows), "",
             "// PARTS: count of days, year, month, day, day of the week (Monday is 0)",
             rows("PARTS", part_rows), "",
             "// OUTSIDE: year, month, day, count of days (years outside 1 to 9999)",
             rows("OUTSIDE", out_rows), "",
             "// BAD: year, month, day of a date that NumPy refuses",
             rows("BAD", bad_rows)]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(len(day_rows) // 4, len(part_rows) // 5, len(out_rows) // 4, len(bad_rows) // 3)


if __name__ == "__main__":
    main()
