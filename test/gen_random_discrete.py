#!/usr/bin/env python3
"""Write the pins of the tests of the discrete random laws.

The script needs SciPy 1.18.1. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. Each law has 3 parameter sets.
A set holds the parameters, the mean, the variance and three
thresholds with the value of the distribution function at each, from
scipy.stats. The tests draw numbers from the generator of the package
and compare them with these values. The stream of the package differs
from the stream of NumPy, so the law is the reference.

The thresholds are the quartiles of the law. The value of the
distribution function at a threshold is the chance of a number at or
below it.
"""
import scipy.stats as st

OUT = "test/suite/random_discrete_pins.goose"

LAWS = {
    "BIN": ([(10, 0.3), (100, 0.5), (50, 0.9)],
            lambda p: st.binom(p[0], p[1])),
    "GEO": ([(0.2,), (0.5,), (0.05,)],
            lambda p: st.geom(p[0])),
    "HYP": ([(10, 20, 12), (50, 30, 60), (5, 95, 30)],
            lambda p: st.hypergeom(p[0] + p[1], p[0], p[2])),
    "LOG": ([(0.3,), (0.7,), (0.95,)],
            lambda p: st.logser(p[0])),
    "NBIN": ([(5.0, 0.4), (2.5, 0.3), (10.0, 0.8)],
             lambda p: st.nbinom(p[0], p[1])),
    "ZIPF": ([(6.0,), (8.0,), (10.0,)],
             lambda p: st.zipf(p[0])),
}


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in values)))


def main():
    lines = ["// Generated by test/gen_random_discrete.py. Do not edit by hand.",
             "",
             "// The pins of the tests of the discrete random laws.",
             "// They come from SciPy 1.18.1.",
             "// Each law holds 3 sets. P1, P2 and P3 are the parameters, M the",
             "// mean, V the variance, T the three thresholds of each set and",
             "// C the value of the distribution function at each threshold.",
             "namespace random_discrete_pins;",
             ""]
    for name, (sets, law_of) in LAWS.items():
        for k in range(len(sets[0])):
            emit(lines, "%s_P%d" % (name, k + 1), [s[k] for s in sets])
        laws = [law_of(p) for p in sets]
        emit(lines, name + "_M", [d.mean() for d in laws])
        emit(lines, name + "_V", [d.var() for d in laws])
        pairs = [(d.ppf(q), d.cdf(d.ppf(q))) for d in laws for q in (0.25, 0.5, 0.75)]
        ts = [t for t, c in pairs]
        cs = [c for t, c in pairs]
        emit(lines, name + "_T", ts)
        emit(lines, name + "_C", cs)
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s, %d laws" % (OUT, len(LAWS)))


if __name__ == "__main__":
    main()
