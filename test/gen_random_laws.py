#!/usr/bin/env python3
"""Write the pins of the tests of the laws of the F family, of
the circle, of the Pareto, of the triangle and of the Wald form.

The script needs SciPy 1.18.1. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. Each law has 3 parameter sets.
A set holds the parameters, the mean, the variance and the quartiles
of the law, from scipy.stats. The tests draw numbers from the generator
of the package and compare them with these values. The stream of the
package differs from the stream of NumPy, so the law is the reference.

The law of the von Mises lies on the circle. Its pins hold a location
of zero, so the quartiles of SciPy are the quartiles of the law. The
pins of that law hold the ratio of the modified Bessel functions,
which is the mean of the cosines of the law.
"""
import scipy.stats as st
from scipy import special

OUT = "test/suite/random_laws_pins.goose"

# The name of each law, its 3 parameter sets and the law of SciPy.
# The law of SciPy is a callable that takes the parameters of the set.
LAWS = {
    "F": ([(5.0, 8.0), (3.0, 20.0), (10.0, 15.0)],
          lambda p: st.f(p[0], p[1])),
    "NCX2": ([(5.0, 2.0), (10.0, 7.5), (0.5, 2.0)],
             lambda p: st.ncx2(p[0], p[1])),
    "NCF": ([(5.0, 8.0, 3.0), (4.0, 10.0, 2.0), (6.0, 20.0, 0.5)],
            lambda p: st.ncf(p[0], p[1], p[2])),
    "PARETO": ([(6.0,), (8.0,), (10.0,)],
               lambda p: st.pareto(b=p[0], loc=-1.0)),
    "TRI": ([(-2.0, 0.0, 3.0), (0.0, 1.0, 2.0), (1.0, 1.0, 4.0)],
            lambda p: st.triang(c=(p[1] - p[0]) / (p[2] - p[0]),
                                loc=p[0], scale=p[2] - p[0])),
    "VM": ([(0.0, 0.5), (0.0, 1.5), (0.0, 4.0)],
           lambda p: st.vonmises(p[1], loc=p[0])),
    "WALD": ([(2.0, 3.0), (1.0, 1.0), (0.5, 0.25)],
             lambda p: st.invgauss(mu=p[0] / p[1], scale=p[1])),
}

# The law of the von Mises holds the ratio of the modified Bessel
# functions of the concentration. It is the mean of the cosines of the
# numbers of the law less the location. The concentrations are the
# second parameters of the sets of that law.
KAPPAS = [s[1] for s in LAWS["VM"][0]]


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" %
                 (name, ", ".join(repr(float(v)) for v in values)))


def main():
    lines = ["// Generated by test/gen_random_laws.py. Do not edit by hand.",
             "",
             "// The pins of the tests of the laws of the F family, of",
             "// the circle, of the Pareto, of the triangle and of the",
             "// Wald form.",
             "// They come from SciPy 1.18.1.",
             "// Each law holds 3 sets. P1, P2 and P3 are the parameters, M the",
             "// mean, V the variance and Q the quartiles, three for each set.",
             "namespace random_laws_pins;",
             ""]
    for name, (sets, law_of) in LAWS.items():
        n = len(sets[0])
        for k in range(n):
            emit(lines, "%s_P%d" % (name, k + 1), [s[k] for s in sets])
        laws = [law_of(p) for p in sets]
        emit(lines, name + "_M", [d.mean() for d in laws])
        emit(lines, name + "_V", [d.var() for d in laws])
        emit(lines, name + "_Q", [d.ppf(q) for d in laws for q in (0.25, 0.5, 0.75)])
    # The ratio of the modified Bessel functions of each concentration.
    emit(lines, "VM_A", [special.ive(1.0, k) / special.ive(0.0, k) for k in KAPPAS])
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s, %d laws" % (OUT, len(LAWS)))


if __name__ == "__main__":
    main()
