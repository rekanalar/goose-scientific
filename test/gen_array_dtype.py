#!/usr/bin/env python3
"""Write the pins of the tests of the type layer.

The script needs NumPy 2.5.4. It runs from the maintainer. The user of
the package installs nothing.

The file it writes holds numbers only. A type is its index in the list
bool, int8, int16, int32, int64, uint8, uint16, uint32, uint64, float16,
float32, float64, complex64, complex128. A matrix holds one row per
first type and one column per second type. A flag is 1.0 or 0.0.
"""
import numpy as np

OUT = "test/suite/array_dtype_pins.goose"
NAMES = ['bool', 'int8', 'int16', 'int32', 'int64', 'uint8', 'uint16', 'uint32',
         'uint64', 'float16', 'float32', 'float64', 'complex64', 'complex128']
CLASSES = ['generic', 'number', 'integer', 'signedinteger', 'unsignedinteger',
           'floating', 'complexfloating', 'inexact']
KINDS = ['bool', 'signed integer', 'unsigned integer', 'integral',
         'real floating', 'complex floating', 'numeric']
INTS = [0, 1, 127, 128, 255, 256, 65535, 65536, 4294967295, 4294967296,
        2 ** 62, -1, -128, -129, -32768, -32769, -2147483648, -2147483649, -2 ** 62]
FLOATS = [0.0, 3.5, -3.5, 64999.0, 65000.0, -65000.0, 65504.0, 1e10, 3.3e38,
          3.4e38, -3.4e38, 1e300, 1e-300, float('nan'), float('inf'), -float('inf')]


def emit(lines, name, values):
    lines.append("const %s: f64[>..] = [%s];" % (name, ", ".join(repr(float(v)) for v in values)))


def index(dt):
    return NAMES.index(np.dtype(dt).name)


def main():
    lines = ["// Generated by test/gen_array_dtype.py. Do not edit by hand.", "",
             "// The pins of the tests of the type layer. They come from NumPy 2.5.4.",
             "namespace array_dtype_pins;", ""]
    dts = [np.dtype(n) for n in NAMES]
    emit(lines, "PROMOTE", [index(np.promote_types(a, b)) for a in dts for b in dts])
    emit(lines, "RESULT", [index(np.result_type(a, b)) for a in dts for b in dts])
    for mode in ('no', 'equiv', 'safe', 'same_kind', 'unsafe'):
        emit(lines, "CAST_" + mode.upper(),
             [1 if np.can_cast(a, b, casting=mode) else 0 for a in dts for b in dts])
    common = []
    for a in NAMES:
        for b in NAMES:
            if a == 'bool' or b == 'bool':
                common.append(-1)
            else:
                common.append(index(np.common_type(np.empty(0, dtype=a), np.empty(0, dtype=b))))
    emit(lines, "COMMON", common)
    emit(lines, "SUB", [1 if np.issubdtype(a, getattr(np, c)) else 0 for a in dts for c in CLASSES])
    emit(lines, "KIND", [1 if np.isdtype(a, k) else 0 for a in dts for k in KINDS])
    emit(lines, "MIN_INT_IN", INTS)
    emit(lines, "MIN_INT_OUT", [index(np.min_scalar_type(v)) for v in INTS])
    finite = [v for v in FLOATS if np.isfinite(v)]
    emit(lines, "MIN_FLOAT_IN", finite)
    emit(lines, "MIN_FLOAT_OUT", [index(np.min_scalar_type(v)) for v in finite])
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
